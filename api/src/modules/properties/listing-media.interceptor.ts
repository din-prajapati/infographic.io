import { BadRequestException, CallHandler, ExecutionContext, FileTypeValidator, ForbiddenException, HttpException, Inject, Injectable, Logger, NestInterceptor, ServiceUnavailableException } from '@nestjs/common';
import { AnyFilesInterceptor } from '@nestjs/platform-express';
import { plainToInstance } from 'class-transformer';
import { validateSync } from 'class-validator';
import { from, lastValueFrom, Observable } from 'rxjs';
import { randomUUID } from 'crypto';
import { createEmptyListing, validateListingRecord } from '@shared/listingWorkflow';
import { validateListingIdentity } from '@shared/listingIdentity';
import { StorageService } from '../storage/services/storage.service';
import { CreatePropertyDto, SaveListingProfileDto, UpdatePropertyDto } from './dto/property.dto';

const MAX_BYTES = 10 * 1024 * 1024;
const EXTENSIONS: Record<string, string> = { 'image/jpeg': 'jpg', 'image/png': 'png', 'image/webp': 'webp', 'image/gif': 'gif', 'image/avif': 'avif' };
export const ListingFilesInterceptor = AnyFilesInterceptor({ limits: { files: 10, fileSize: MAX_BYTES, fields: 1, fieldSize: 12 * 1024 * 1024, parts: 11 } });
interface FileUpload { fieldname: string; mimetype: string; buffer: Buffer; size: number }

/**
 * Workspace saves can include local draft files. Existing JSON/editor clients are unchanged.
 * Validate everything first, upload only on explicit Save, then persist durable URLs through the normal handler.
 * Rollback deletes only keys generated by this request, never a previously saved/shared object.
 */
@Injectable()
export class ListingMediaInterceptor implements NestInterceptor {
  private readonly logger = new Logger(ListingMediaInterceptor.name);
  constructor(@Inject(StorageService) private readonly storage: StorageService) {}

  intercept(context: ExecutionContext, next: CallHandler): Observable<unknown> {
    const req = context.switchToHttp().getRequest();
    if (!req.is('multipart/form-data')) return next.handle();
    return from(this.save(req, next));
  }

  private async save(req: any, next: CallHandler) {
    if (!req.body || Object.keys(req.body).length !== 1 || typeof req.body.payload !== 'string') throw new BadRequestException('Expected one listing payload.');
    let body: any;
    try { body = JSON.parse(req.body.payload); } catch { throw new BadRequestException('Invalid listing payload.'); }
    const isProfile = req.path.replace(/\/$/, '').endsWith('/listing-profiles');
    const dto = isProfile ? SaveListingProfileDto : req.method === 'POST' ? CreatePropertyDto : UpdatePropertyDto;
    if (!body || typeof body !== 'object' || Array.isArray(body) || validateSync(plainToInstance(dto, body), { whitelist: true, forbidNonWhitelisted: true }).length) throw new BadRequestException('Invalid listing payload or version.');
    if (!isProfile && !req.user.organizationId) throw new ForbiddenException('An organization is required to save properties');
    const record = body.record;
    if (!record || typeof record !== 'object' || Array.isArray(record)) throw new BadRequestException('Expected a listing record.');
    if (isProfile && Object.keys(record).some(key => key !== 'agent' && key !== 'brand')) throw new BadRequestException('Expected agent and brand profile.');
    const files: FileUpload[] = req.files ?? [];
    const references = new Map<string, { target: any; key: string }[]>();
    const add = (target: any, key: string) => {
      if (!target || typeof target[key] !== 'string' || !target[key].startsWith('draft:')) return;
      const id = target[key].slice(6);
      references.set(id, [...(references.get(id) ?? []), { target, key }]);
      target[key] = 'https://draft.invalid/image';
    };
    add(record.agent, 'photo'); add(record.brand, 'logo');
    if (Array.isArray(record.photos)) for (const photo of record.photos) add(photo, 'src');
    const full = isProfile ? { ...createEmptyListing(), agent: undefined, brand: undefined, ...record } : record;
    const errors = validateListingRecord(full);
    if (!errors.length) errors.push(...validateListingIdentity(full));
    if (errors.length) throw new BadRequestException(errors);
    if (files.length !== references.size || new Set(files.map(file => file.fieldname)).size !== files.length || files.some(file => !references.has(file.fieldname))) throw new BadRequestException('Every draft image must have exactly one uploaded file.');
    const validator = new FileTypeValidator({ fileType: /^image\/(jpeg|png|webp|gif|avif)$/ });
    for (const file of files) {
      if (!EXTENSIONS[file.mimetype] || file.size > MAX_BYTES || !await validator.isValid(file)) throw new BadRequestException('Choose a JPEG, PNG, WebP, GIF or AVIF image smaller than 10 MB.');
    }
    if (files.length && !/^https:\/\//.test(process.env.R2_PUBLIC_URL ?? '')) throw new ServiceUnavailableException('Image storage is unavailable. Retry saving.');
    const keys: string[] = [];
    let handlerStarted = false;
    try {
      const owner = (req.user.organizationId || `user-${req.user.id}`).replace(/[^a-zA-Z0-9_-]/g, '');
      for (const file of files) {
        const key = `design-media/${owner}/${randomUUID()}.${EXTENSIONS[file.mimetype]}`;
        keys.push(key);
        await this.storage.upload(file.buffer, key, file.mimetype);
        for (const reference of references.get(file.fieldname)!) reference.target[reference.key] = this.storage.getPublicUrl(key);
      }
      req.body = body;
      handlerStarted = true;
      return await lastValueFrom(next.handle());
    } catch (error) {
      // An unknown DB/connection error may mean the write committed. Preserve its media instead of breaking saved data.
      const rejected = error instanceof HttpException && error.getStatus() < 500;
      if (!handlerStarted || rejected) {
        await Promise.all(keys.map(async key => {
          try { await this.storage.remove(key); }
          catch { this.logger.error(JSON.stringify({ event: 'listing-media:cleanup-failed', key, userId: req.user.id })); }
        }));
      } else if (keys.length) this.logger.warn(JSON.stringify({ event: 'listing-media:save-uncertain', keys, userId: req.user.id }));
      if (!handlerStarted && !(error instanceof HttpException)) throw new ServiceUnavailableException('Image upload failed. Your changes are kept; retry saving.');
      throw error;
    }
  }
}
